/**
 * "Pro spots": dealer-grade offer ads (lease / APR / cash / trade / price /
 * event). The offer text is parsed into structured fields the layouts need —
 * and nothing is invented: terms that aren't in the offer stay out of the ad.
 */

import type { OfferDetail } from "./types";

export type SpotKind = "lease" | "apr" | "cash" | "trade" | "price" | "event" | "generic";

export type SpotFields = {
  kind: SpotKind;
  /** Small boxed line above the headline, e.g. "LEASE A NEW". */
  kicker: string;
  /** Big stacked headline lines. */
  lines: string[];
  /** Hero number, e.g. "$319" or "0.99%". */
  big?: string;
  /** Unit next to the hero number, e.g. "/MO", "APR", "OFF". */
  unit?: string;
  /** Supporting line, only from the offer text (e.g. "for 36 months"). */
  detail?: string;
  /** Right-hand badge in the diagonal panel. */
  badge?: string;
  cta: string;
  disclaimer: string;
  scene: string;
  /** A dealer-generated background, embedded so saved ads render on their own. */
  customScene?: Scene;
};

/**
 * A background the car is composited into. The fit data lets any car sit on
 * the road like it was shot there: the scene is shifted/scaled so its horizon
 * cuts the car at eye level, the road's centre runs under the tyres, and the
 * car picks up the scene's light (tint), shadow and floor reflection.
 */
export type Scene = {
  id: string;
  label: string;
  src: string;
  /** Eye-level horizon / road vanishing point, 0–1 of image height. */
  horizon: number;
  /** Road centre near the bottom of the frame, 0–1 of image width. */
  roadX: number;
  /** Ambient light colour washed over the car, and how strongly (0–1). */
  tint: string;
  tintAmount: number;
  /** Contact-shadow strength (0–1) and wet/glossy floor reflection (0–1). */
  shadow: number;
  reflect: number;
  dark: boolean;
  /** AI-generated by the dealer. */
  custom?: boolean;
  prompt?: string;
};

