/**
 * Light the car to match a generated scene: average colour and brightness of
 * the image decide the tint, and dark scenes get the car darkened to match.
 */
export function estimateLight(img: CanvasImageSource & { width: number; height: number }) {
  const c = document.createElement("canvas");
  c.width = 24;
  c.height = 42;
  const x = c.getContext("2d", { willReadFrequently: true })!;
  x.drawImage(img, 0, 0, 24, 42);
  let d: Uint8ClampedArray;
  try {
    d = x.getImageData(0, 0, 24, 42).data;
  } catch {
    return { tint: "#ffffff", tintAmount: 0.05, dark: false };
  }
  let r = 0, g = 0, b = 0;
  const n = d.length / 4;
  for (let i = 0; i < d.length; i += 4) {
    r += d[i];
    g += d[i + 1];
    b += d[i + 2];
  }
  r /= n;
  g /= n;
  b /= n;
  const lum = (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255;
  const hex = (v: number) => Math.round(v).toString(16).padStart(2, "0");
  const dark = lum < 0.32;
  // darker scenes darken the car more; bright ones just pick up a little colour
  const tintAmount = dark ? Math.min(0.5, 0.25 + (0.32 - lum)) : 0.06 + Math.min(0.12, Math.abs(r - b) / 600);
  const k = dark ? 0.5 : 1;
  return { tint: `#${hex(r * k)}${hex(g * k)}${hex(b * k)}`, tintAmount, dark };
}

