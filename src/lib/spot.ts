const up = (s: string) => s.toUpperCase().replace(/\s+/g, " ").trim();

/** Model name inside an offer ("Lease a new 2027 Camry LE for…" → "2027 CAMRY LE"). */
function modelFrom(offer: string, vehicleName: string) {
  const m = offer.match(/\bnew\s+((?:19|20)\d{2}\s+)?([A-Z][\w-]*(?:\s+(?!for\b|at\b|with\b|and\b|on\b)[A-Za-z0-9][\w-]*){0,2})/);
  if (m) return up((m[1] ?? "") + m[2]);
  const v = vehicleName.replace(/^(new|used|certified)\s+/i, "");
  return /your next car|special offer/i.test(v) ? "" : up(v.split(" ").slice(0, 4).join(" "));
}

/** Split a phrase into ≤3 stacked lines, widening lines until every word fits — never drops words. */
function stack(text: string, max = 11) {
  const words = up(text).split(" ");
  for (let m = max; m <= 40; m++) {
    const out: string[] = [];
    let cur = "";
    for (const w of words) {
      const next = cur ? cur + " " + w : w;
      if (next.length > m && cur) {
        out.push(cur);
        cur = w;
      } else cur = next;
    }
    if (cur) out.push(cur);
    if (out.length <= 3) return out;
  }
  return [up(text)];
}

/** Claude's reading of this exact offer, if the scan had one. */
export function offerDetailFor(brand: { offerDetails?: OfferDetail[] }, offer: string) {
  const o = offer.trim().toLowerCase();
  return brand.offerDetails?.find((d) => d.headline.trim().toLowerCase() === o);
}

/** The site's own terms beat our defaults: real fine print, real term / due-at-signing line. */
export function withDetail(f: SpotFields, d?: OfferDetail): SpotFields {
  if (!d) return f;
  const terms = [d.term, d.dueAtSigning && `${d.dueAtSigning} due at signing`, d.expires && `ends ${d.expires}`].filter(Boolean).join(" · ");
  return { ...f, disclaimer: d.disclaimer || f.disclaimer, detail: f.detail ?? (terms || undefined) };
}

export function parseOffer(offer: string, vehicleName: string, dealer: string, eventName?: string): SpotFields {
  const o = offer.trim();
  const model = modelFrom(o, vehicleName);
  const months = o.match(/(\d{2})\s*(?:-|\s)?\s*(?:months?|mos?)\b/i)?.[1];
  const due = o.match(/\$\s?([\d,]+)\s*(?:due at signing|down)/i)?.[1];
  const base = {
    cta: "SHOP NOW",
    disclaimer: `Offer subject to credit approval and availability. Not all buyers will qualify. See ${dealer} for complete details.`,
    scene: "city",
  };

  if (/trade/i.test(o)) {
    const amt = o.match(/\$\s?([\d,]+)/)?.[1];
    return { ...base, kind: "trade", kicker: "WHAT'S YOUR", lines: ["TRADE", "VALUE"], big: amt ? `$${amt}` : undefined, unit: amt ? "BONUS" : undefined, badge: "Instant trade-in offer", cta: "FIND OUT NOW" };
  }
  const lease = /lease/i.test(o) && o.match(/\$\s?([\d,]+)\s*(?:\/\s?mo|per month|a month|mo\b)/i);
  if (lease) {
    return {
      ...base,
      kind: "lease",
      kicker: "LEASE A NEW",
      lines: model ? stack(model, 14) : ["THIS WEEK"],
      big: `$${lease[1]}`,
      unit: "/MO",
      detail: [months && `for ${months} months`, due && `$${due} due at signing`].filter(Boolean).join(" · ") || undefined,
      cta: "LEASE NOW",
    };
  }
  const apr = o.match(/(\d+(?:\.\d+)?)\s*%\s*APR/i);
  if (apr) {
    return {
      ...base,
      kind: "apr",
      kicker: model ? "FINANCE A NEW" : "SPECIAL FINANCING",
      lines: model ? stack(model, 14) : ["ON SELECT", "MODELS"],
      big: `${apr[1]}%`,
      unit: "APR",
      detail: months ? `for up to ${months} months` : undefined,
      cta: "GET APPROVED",
    };
  }
  const cash = o.match(/\$\s?([\d,]+)\s*(off|bonus|cash back|cash|rebate|savings|under msrp)/i);
  if (cash) {
    return { ...base, kind: "cash", kicker: /up to/i.test(o) ? "SAVE UP TO" : "SAVE", lines: model ? stack(model, 14) : ["THIS WEEK"], big: `$${cash[1]}`, unit: up(cash[2]).replace("CASH BACK", "BACK").replace("UNDER MSRP", "OFF MSRP"), cta: "CLAIM OFFER" };
  }
  const price = o.match(/\$\s?([\d,]{4,})/);
  if (price) {
    return {
      ...base,
      kind: "price",
      kicker: /move|clearance/i.test(o) ? "PRICED TO MOVE" : "NOW ONLY",
      lines: model ? stack(model, 14) : ["THIS WEEK"],
      big: `$${price[1]}`,
      cta: "SEE IT TODAY",
    };
  }
  if (eventName) {
    return { ...base, kind: "event", kicker: up(dealer).slice(0, 28), lines: stack(eventName.replace(/ (Sales Event|Sale)$/i, ""), 11), detail: o, cta: "SHOP THE EVENT" };
  }
  return { ...base, kind: "generic", kicker: "THIS WEEK ONLY", lines: stack(o, 11), cta: "SHOP NOW" };
}
